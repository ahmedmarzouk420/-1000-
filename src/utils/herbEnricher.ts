function getArabicHeritageForHerb(name: string, system: string, target: string): string {
  for (const [key, quote] of Object.entries(CLASSICAL_ARABIC_HERITAGE_MAP)) {
    if (name.includes(key) || key.includes(name)) {
      return quote;
    }
  }

  return `نصت كتب التراث الطبي العربي ودساتير الأعشاب المعتمدة (القانون لابن سينا والجامع لابن البيطار) على خصائص ${name} في دعم توازن ${system}. اضغط على زر المراجعة بالذكاء الاصطناعي لاستخراج نص الاقتباس الدقيق والمزاج الطبي المعتمد.`;
}

export function enrichHerbWithDetailedExplanation(herb: HerbItem): HerbItem {
  if (herb.aiReviewed) {
    return herb;
  }

  const name = herb.nameAr;
  const scientific = herb.scientific ? ` (${herb.scientific})` : "";
  const system = herb.system || "الصحة العامة";
  const target = herb.target || "دعم الوظائف الحيوية والتوازن الطبيعي";
  const active = herb.active && herb.active.trim() !== "" ? herb.active : "مستخلصات نباتية طبيعية (بانتظار المراجعة الذكية)";
  const prep = herb.preparation || "منقوع عشبي دافئ أو مستخلص قياسي";
  const dose = herb.dose || "ملعقة صغيرة في 200 مل ماء مغلي مرة إلى مرتين يومياً";

  const heritageCitation =
    herb.arabicHeritageCitation && herb.arabicHeritageCitation.trim().length > 20
      ? herb.arabicHeritageCitation.trim()
      : getArabicHeritageForHerb(name, system, target);

  let currentReferences = herb.references || "";
  if (!currentReferences) {
    currentReferences = "كتاب الطب النبوي (ابن قيم الجوزية)، القانون في الطب (ابن سينا)، الجامع لمفردات الأدوية والأغذية (ابن البيطار)، دراسات منظمة الصحة العالمية (WHO Monographs).";
  }

  const hasCustomDescription =
    herb.description &&
    herb.description.trim().length > 25 &&
    !herb.description.includes("مركبات فلافونويدية وزيوت طيارة فعالة");

  const generatedDescription = hasCustomDescription
    ? herb.description!.trim()
    : `مستحضر ${name}${scientific} العضوي الطبيعي المعتمد في صيدلية ومتجر 1000 عشبة الطبية لدعم صحة ${system}. يتميز هذا الصنف بجودة أوراقه ومستخلصاته النقية لتحقيق ${target}. يُنصح بالاستفادة من زر المراجعة بالذكاء الاصطناعي لتوليد بطاقة سريرية وتراثية مخصصة بالكامل لهذا الصنف.`;

  const hasCustomPharmacology =
    herb.pharmacology &&
    herb.pharmacology.trim().length > 20 &&
    !herb.pharmacology.includes("مركبات فلافونويدية وزيوت طيارة فعالة");

  const generatedPharmacology = hasCustomPharmacology
    ? herb.pharmacology!.trim()
    : `تعتمد الخواص الحيوية لـ ${name} على التفاعل الطبيعي للمركبات الفعالة مع خلايا وأنسجة ${system} لتحقيق ${target}. قم بالنقر على مراجعة بالذكاء الاصطناعي لاستخراج مسارات التأشير الإنزيمية والدوائية الدقيقة.`;

  let generatedBenefits = herb.benefits;
  if (!generatedBenefits || generatedBenefits.length === 0) {
    generatedBenefits = [
      `الاستهداف الحيوي: ${target}`,
      `دعم وتنشيط وظائف ${system} بعناصر عشبية نقية`,
      `طريقة التحضير الصيدلاني المثلى: ${prep}`,
      `درجة الأمان: ${herb.safetyLevel || "آمن بالجرعات المعتدلة"} وفق المراجع المعتمدة`,
    ];
  }

  return {
    ...herb,
    arabicHeritageCitation: heritageCitation,
    references: currentReferences,
    description: generatedDescription,
    pharmacology: generatedPharmacology,
    benefits: generatedBenefits,
  };
}

export function enrichHerbsList(herbs: HerbItem[]): HerbItem[] {
  return herbs.map(enrichHerbWithDetailedExplanation);
}
